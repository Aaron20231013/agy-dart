import test from "node:test";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import {spawnSync} from "node:child_process";
import {fileURLToPath} from "node:url";
import {ContextModeStore} from "../context/lib/store.js";
import assert from "node:assert/strict";
import {extractSymbolsFromLines,renderOutlineWithinBudget} from "../context/lib/code-outline.js";
test("v1.7 compact TS signatures and wrapped suites",t=>{
  const source=["function parse(","  x: string","): { ok: boolean }","{"," return {ok:true};","}"];
  const [s]=extractSymbolsFromLines("a.ts",source);
  assert.equal(s.endLine,6);
  assert.match(s.signature,/parse\(\s*x: string\s*\): \{ ok: boolean \}/);
  const secret = "sk-" + "test0123456789abcdef".repeat(2);
  const redacted = extractSymbolsFromLines("a.js",['function load(key = "' + secret + '") {}']);
  assert.ok(redacted[0].signature && !redacted[0].signature.includes(secret));
  assert.equal(extractSymbolsFromLines("a.ts",["function long("+ "param,".repeat(40) +"z) {}"])[0].signature.length,96);
  const tmp=fs.mkdtempSync(path.join(os.tmpdir(),"agy-map-"));
  t.after(()=>fs.rmSync(tmp,{recursive:true,force:true}));
  const paths=Array.from({length:35},(_,i)=>path.join(tmp,"模块-"+i+".ts"));
  for(const file of paths) fs.writeFileSync(file,source.join("\n"));
  const db=path.join(tmp,"cache.db");
  const store=new ContextModeStore({dbPath:db});
  const stat=fs.statSync(paths[0]);
  store.setOutlineCache(paths[0],stat.mtimeMs,stat.size,1,[{name:"STALE",kind:"class",startLine:1,endLine:1,depth:0}]);
  store.close();
  const req={jsonrpc:"2.0",id:7,method:"tools/call",params:{name:"read_slices",arguments:{cwd:tmp,outlines:paths}}};
  const env={...process.env,HOME:tmp,USERPROFILE:tmp,AGY_DART_CONFIG_PATH:path.join(tmp,"cfg.json"),AGY_DART_DB_PATH:db};
  const server=fileURLToPath(new URL("../fast/mcp-server.mjs",import.meta.url));
  const rpc=spawnSync(process.execPath,[server],{input:JSON.stringify(req)+"\n",env,encoding:"utf8"});
  assert.equal(rpc.status,0,rpc.stderr); assert.equal(rpc.stderr,"");
  const line=rpc.stdout.trimEnd(); assert.ok(Buffer.byteLength(line+"\n")<=8800);
  const response=JSON.parse(line);assert.equal(response.result.isError,false,response.result.content[0].text);
  for(const file of paths) assert.ok(response.result.content[0].text.includes(path.basename(file)));
  assert.doesNotMatch(line,/STALE/);
  try {assert.match(store.getOutlineCache(paths[0],stat.mtimeMs,stat.size,2).symbols[0].signature,/parse\(/);} finally {store.close();}
  const wrapped=["(function(){","  function inner(a) {}","  describe.concurrent('中文',()=>{});","  it.each([1])('case',()=>{});","})();"];
  assert.deepEqual(extractSymbolsFromLines("a.js",wrapped).map(x=>x.name),["inner","中文","case"]);
  const symbols=Array.from({length:160},(_,i)=>({...s,name:"名称"+i,signature:"函数"+"字".repeat(24)}));
  const block=renderOutlineWithinBudget("中文.ts",400,symbols,3400,1);
  assert.ok(Buffer.byteLength(block)<=3400);
  assert.match(block,/more symbols/);
});
